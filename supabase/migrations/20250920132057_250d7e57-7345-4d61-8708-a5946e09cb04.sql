-- Add some celebrity events
INSERT INTO celebrity_events (
  celebrity_id,
  title,
  description,
  event_date,
  location,
  event_type,
  is_public
) 
SELECT 
  c.id,
  CASE 
    WHEN c.category = 'Actors' THEN 'Movie Premiere'
    WHEN c.category = 'Athletes' THEN 'Sports Event'
    ELSE 'Fan Meet'
  END as title,
  'Meet and greet with fans' as description,
  CURRENT_DATE + INTERVAL '30 days' as event_date,
  c.location,
  'public_event' as event_type,
  true as is_public
FROM celebrities c
WHERE c.name IN ('Shah Rukh Khan', 'Priyanka Chopra', 'Virat Kohli')
LIMIT 3;